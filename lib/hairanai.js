/* hairanai.js — ★書き出す ファイルに「入らない 物」を 数えて 言葉に する★（2026-09-06）
 *
 *  ★★なぜ 要るか（2026-09-06 実測）★★
 *    受け取った ファイルを 保存し直す 道（`saveOpenedBook`）は
 *    ★元の zip を 持ったまま ★値だけ★ 書き戻す★。
 *    ⇒★預かった 物は 1バイトも 壊れない★（08-30 実測ずみ・良い所）
 *    ⇒★でも うちで 足した 物は 書き出す 先に 入らない★
 *      実測 … 新しいシートを 1枚 足して 保存 ⇒ ★出た ファイルに 無い★
 *      場所 … `js/book-open.js` `saveXlsxLike()`
 *             `if (opened.sheetNames.indexOf(sh.name) < 0) return;`
 *
 *  ★★一番 悪いのは「黙って 消える」事★★
 *    画面は「値だけ 書き換えました」としか 言わない。
 *    ⇒「触っていません」は ★守った★と 読める／
 *      ★「入りません」とは 一言も 書いていない★
 *    ⇒ お客さんから 見れば ★自分の 仕事が 黙って 消える★
 *
 *  ★ここで する事★＝★数えて 言葉に するだけ★（消さない・止めない）
 *    ★「するな」の 横に 行き先★（2026-09-06 の 決まり）＝
 *      入らない と 言うだけでは なく ★どうすれば 残るか★も 1行 付ける。
 *
 *  ★ここは 純粋な 計算だけ★＝node で そのまま 試験できる。
 *  見張り: tests/hairanai.test.mjs
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Hairanai = factory();
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /** ★入らない 物を 数える★
   *  ★★名前を `数える` に しない★★（2026-09-06 実測で 踏んだ）
   *    `lib/*.js` には `数える(…)` が 5つ 在る（ctx-menu／ribbon 系）。
   *    ★`tests/unused-param.test.mjs` は ★名前で★ 呼び出しを 見る★ので、
   *    ここに `数える(a,b,c)` を 足すと ★その 5つが「呼ばれている」事に なる★
   *    ⇒★候補が 15個 → 10個に 減り、★見張りが 5個 見えなく なった★★
   *    ⇒★★私の 名前の 付け方が 別の 見張りを 騙していた★★
   *  @param 元のシート名 開いた ファイルに 在る シート名（配列）
   *  @param 今のシート   画面の sheets（[{name, data}]）
   *  @param 浮かぶ物     {グラフ:n, 図形:n, 画像:n, 付箋:n, スパークライン:n …}（省略可）
   *  @returns {{件:number, 中身:Array<{何:string, 数:number, どこ:string}>}}
   */
  function 入らない物を数える(元のシート名, 今のシート, 浮かぶ物) {
    const 元 = {};
    (元のシート名 || []).forEach(function (n) { 元[n] = true; });
    const 中身 = [];

    /* ①うちで 足した シート（★一番 確か＝コードが はっきり 飛ばしている★） */
    const 足したシート = (今のシート || [])
      .map(function (s) { return s && s.name; })
      .filter(function (n) { return n && !元[n]; });
    if (足したシート.length) {
      中身.push({
        何: '新しいシート', 数: 足したシート.length,
        どこ: 足したシート.join('／')
      });
    }

    /* ②浮かぶ物（グラフ・図形・画像・付箋 …）
       ★数は 呼ぶ側が 数えて 渡す★＝ここで 画面を 触らない（純粋なまま） */
    /* ★数える 名前は 画面の 入れ物に 合わせる★＝勝手に 分類しない
       book.html の 実物 … sheets[i].objects（図形・グラフ・画像が 同じ 箱）／
                          comments（付箋）／sparklines
       ⇒★箱が 1つなら 名前も 1つに する★（分けて 見せると 数が 合わなくなる） */
    const 順 = ['図形・グラフ・画像', '付箋', 'スパークライン'];
    for (let i = 0; i < 順.length; i++) {
      const k = 順[i];
      const n = (浮かぶ物 && Number(浮かぶ物[k])) || 0;
      if (n > 0) 中身.push({ 何: k, 数: n, どこ: '' });
    }

    let 件 = 0;
    for (let j = 0; j < 中身.length; j++) 件 += 中身[j].数;
    return { 件: 件, 中身: 中身 };
  }

  /** ★お客さんへの 言葉★（3行）
   *  ★★お客さんに 出す 字に ★ を 使わない★★（2026-09-06 指示役）
   *    ★ は ★私たちの 便りの 印★＝お客さんには ★壊れた 字★に 見える。
   *    強調は ★色と 太字★でやる（画面側の .hairanai）。
   *    ⇒ 同じ日に Rakunally も 23件 直している（会社ぜんぶの 決まり）。
   *  ★★「今」と「これから」を 混ぜない★★
   *    前は「今 出来る 事： …口を 用意します（まだ 有りません）」と 書いていた
   *    ＝★見出しが 約束して 中身が 裏切る★。分けた。
   *  ★★短く★★＝お客さんは ★書き出す 直前＝急いでいる★。1行目だけで 分かる形。
   *  @returns {string} 0件なら 空の 字（★何も 出さない★） */
  function 言葉(出) {
    if (!出 || !出.件) return '';
    const 並び = 出.中身.map(function (x) {
      return x.何 + ' ' + x.数 + (x.何 === '新しいシート' ? '枚' : '個')
        + (x.どこ ? '（' + x.どこ + '）' : '');
    }).join('／');
    return '入りません： ' + 並び
      + '\n元の ファイルの 罫線・判子・グラフは そのまま 残ります。'
      + '\n上の 物は 画面の 中だけに 残ります（別ファイルに 書き出す 口は これから）。';
  }

  /** ★短い 一行★（帯や 知らせ 用） */
  function 一行(出) {
    if (!出 || !出.件) return '';
    return 出.件 + '個は この ファイルに 入りません（うちで 足した 物）';
  }

  return { 入らない物を数える: 入らない物を数える, 言葉: 言葉, 一行: 一行 };
}));
