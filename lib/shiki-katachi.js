/* shiki-katachi.js — ★切った かたまりを「形」に する★（2026-09-11）
 *
 *  ★★土台を 自分で 作る ②枚目★★（①は `lib/shiki-kiru.js`＝字に 切る）
 *    土台は 5つ … ①読む ②★形に する★ ③頼りの 地図 ④順番と 計算 ⑤溢れ
 *
 *  ★★借り物の 中は 1文字も 読んで いません★★
 *    形は ★実Excel が 受ける 字★から 決めます。
 *
 *  ★★測り方＝形から 字に 戻したら 元と 1バイトも 違わない事★★
 *    ⇒★取りこぼしも 足しすぎも 0★の 証し（実Excel を 呼ばずに 測れる）
 *    実測 … 司さんの 実物 15,799本
 *
 *  ★形の 種類★
 *    {種:'数', 値} ／ {種:'字', 値} ／ {種:'誤', 値}
 *    {種:'名', 値}            … 参照・TRUE・名前
 *    {種:'呼', 名, 引数:[…]}  … 関数（SUM(...)）
 *    {種:'二', 記, 左, 右}    … 2つを つなぐ（+ - * / ^ & = <> < > <= >= : 空白）
 *    {種:'前', 記, 子}        … 前に 付く（- +）
 *    {種:'後', 記, 子}        … 後ろに 付く（%）
 *    {種:'括', 子}            … ( )
 *    {種:'配', 行:[[…]]}      … {1,2;3,4}
 *
 *  ★読めない 時は 断ります★（壊すより 断る）
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.ShikiKatachi = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /* ★力の 強さ★（実Excel の 決まり・強い ほど 先に 結ぶ）
     ★当て推量では ありません★＝下の 見張りで 実Excel の 答えと 突き合わせます */
  var 強さ = {
    ':': 8, ' ': 7, ',': 6,
    '^': 5,
    '*': 4, '/': 4,
    '+': 3, '-': 3,
    '&': 2,
    '=': 1, '<>': 1, '<': 1, '>': 1, '<=': 1, '>=': 1
  };

  function 作る(かたまり) {
    var i = 0;

    /* ★★ただの 空白は 飛ばします★★（2026-09-11 実物で 10,575本が ここで 止まった）
       `MATCH(B4, Table1[#Data], 0)` の ように ★区切りの 後ろに 空白★が 在ります。
       ★ただし 2つの 間に 挟まる 空白は「交わり」という 意味を 持ちます★
         `=SUM(A1:A3 B1:B3)` … A1:A3 と B1:B3 の ★重なった 所★
       ⇒★前が「物の 終わり」で 後ろが「物の 始まり」の 時だけ 交わり★
         それ以外（区切りの 後・括弧の 後 など）は ★ただの 飾り★＝飛ばす */
    function 物の終わりか(x) {
      if (!x) return false;
      if (x.型 === '数' || x.型 === '字' || x.型 === '誤' || x.型 === '名') return true;
      return x.型 === '記' && (x.字 === ')' || x.字 === '}' || x.字 === '%');
    }
    function 物の始まりか(x) {
      if (!x) return false;
      if (x.型 === '数' || x.型 === '字' || x.型 === '誤' || x.型 === '名') return true;
      return x.型 === '記' && (x.字 === '(' || x.字 === '{' || x.字 === '-' || x.字 === '+');
    }
    function 飾りの空白か(n) {
      var x = かたまり[n];
      if (!x || x.型 !== '記' || x.字 !== ' ') return false;
      return !(物の終わりか(かたまり[n - 1]) && 物の始まりか(かたまり[n + 1]));
    }
    /* ★★飾りの 空白も 覚えて おきます★★（2026-09-11）
       捨てると ★元の 字に 戻りません★＝「1バイトも 違わない」で 測れなく なります。
       ⇒★次の かたまりに くっつけて 持ちます★（`前空白`）
       ⇒ 計算する 時は 見ません（飾りなので） */
    var 溜め = '';
    function 飛ばす() { while (飾りの空白か(i)) { 溜め += かたまり[i].字; i++; } }
    function 空白を取る() { var s = 溜め; 溜め = ''; return s; }

    function 今() { 飛ばす(); return かたまり[i]; }
    function 進む() { 飛ばす(); return かたまり[i++]; }
    function 記号か(x, 字) { return x && x.型 === '記' && x.字 === 字; }

    function 一つ() {
      var t = 今();
      var 前空白 = 空白を取る();
      if (!t) throw new Error('★式が 途中で 終わって いる★');

      /* ★前に 付く 記号★ */
      if (記号か(t, '-') || 記号か(t, '+')) {
        進む();
        return 後ろの記号({ 種: '前', 記: t.字, 子: 一つ(), 空: 前空白 });
      }
      /* ★括弧★ */
      if (記号か(t, '(')) {
        進む();
        var 中 = 式();
        if (!記号か(今(), ')')) throw new Error('★閉じ括弧が 無い★');
        var 閉前 = 空白を取る(); 進む();
        return 後ろの記号({ 種: '括', 子: 中, 空: 前空白, 閉空: 閉前 });
      }
      /* ★配列★ */
      if (記号か(t, '{')) {
        進む();
        var 行 = [], 列 = [];
        for (;;) {
          列.push(式());
          if (記号か(今(), ',')) { 進む(); continue; }
          if (記号か(今(), ';')) { 進む(); 行.push(列); 列 = []; continue; }
          break;
        }
        if (!記号か(今(), '}')) throw new Error('★閉じ中括弧が 無い★');
        進む();
        行.push(列);
        return 後ろの記号({ 種: '配', 行: 行, 空: 前空白 });
      }
      /* ★数・字・誤★ */
      if (t.型 === '数' || t.型 === '字' || t.型 === '誤') {
        進む();
        return 後ろの記号({ 種: t.型 === '数' ? '数' : (t.型 === '字' ? '字' : '誤'), 値: t.字, 空: 前空白 });
      }
      /* ★名前★＝後ろに ( が 来たら 関数 */
      if (t.型 === '名') {
        進む();
        if (記号か(今(), '(')) {
          進む();
          var 引数 = [], 区切り前 = [];
          if (!記号か(今(), ')')) {
            for (;;) {
              引数.push(式());
              /* ★★区切りの「前」の 空白も 覚えます★★（2026-09-11 見張りが 捕まえた）
                 `SUM( 1 , 2 )` … `1` の 後ろの 空白が 落ちて
                 `SUM( 1,  2 )` に なって いました（★字に 戻らない★） */
              var 前空 = '';
              if (記号か(今(), ',')) { 前空 = 空白を取る(); 区切り前.push(前空); 進む(); continue; }
              break;
            }
          }
          if (!記号か(今(), ')')) throw new Error('★関数の 閉じ括弧が 無い★');
          var 閉前 = 空白を取る(); 進む();
          return 後ろの記号({ 種: '呼', 名: t.字, 引数: 引数, 区切り前: 区切り前, 空: 前空白, 閉空: 閉前 });
        }
        return 後ろの記号({ 種: '名', 値: t.字, 空: 前空白 });
      }
      throw new Error('★読めない かたまり「' + t.字 + '」★');
    }

    /* ★後ろに 付く 記号（%）★ */
    function 後ろの記号(子) {
      while (記号か(今(), '%')) { 進む(); 子 = { 種: '後', 記: '%', 子: 子 }; }
      return 子;
    }

    /* ★2つを つなぐ★＝強い 物から 結ぶ */
    function 式(下限) {
      下限 = 下限 || 0;
      var 左 = 一つ();
      for (;;) {
        var t = 今();
        if (!t || t.型 !== '記') break;
        var 力 = 強さ[t.字];
        if (力 === undefined || 力 <= 下限) break;
        if (t.字 === ',' || t.字 === ';') break;      /* ★区切りは ここで 結ばない★ */
        進む();
        var 右 = 式(力);
        左 = { 種: '二', 記: t.字, 左: 左, 右: 右 };
      }
      return 左;
    }

    var 出 = 式();
    飛ばす();
    if (i !== かたまり.length) {
      throw new Error('★終わりまで 読めて いない★（' + i + ' / ' + かたまり.length + '）');
    }
    return 出;
  }

  /**
   * ★かたまりを 形に する★
   * @returns {{ok:boolean, 形:object|null, なぜ:string}}
   */
  function 形にする(かたまり) {
    try {
      var 頭 = 0;
      if (かたまり.length && かたまり[0].型 === '＝') 頭 = 1;
      return { ok: true, 形: 作る(かたまり.slice(頭)), なぜ: '' };
    } catch (e) {
      return { ok: false, 形: null, なぜ: e.message };
    }
  }

  /** ★形から 字に 戻す★＝元に 戻るかを 測る為（★測りの 芯★） */
  function 字に戻す(形) {
    if (!形) return '';
    var 空 = 形.空 || '';          /* ★前に 在った 飾りの 空白★ */
    var 閉 = 形.閉空 || '';        /* ★閉じ括弧の 前の 空白★ */
    switch (形.種) {
      case '数': case '字': case '誤': case '名': return 空 + 形.値;
      case '前': return 空 + 形.記 + 字に戻す(形.子);
      case '後': return 字に戻す(形.子) + 形.記;
      case '括': return 空 + '(' + 字に戻す(形.子) + 閉 + ')';
      case '二': return 字に戻す(形.左) + 形.記 + 字に戻す(形.右);
      case '呼': {
        var 区 = 形.区切り前 || [];
        var 中 = '';
        for (var n = 0; n < 形.引数.length; n++) {
          if (n) 中 += ',';
          中 += 字に戻す(形.引数[n]) + (n < 形.引数.length - 1 ? (区[n] || '') : '');
        }
        /* ★区切りの 前の 空白は その 引数の 後ろに 出す★ */
        中 = '';
        for (var m = 0; m < 形.引数.length; m++) {
          中 += 字に戻す(形.引数[m]);
          if (m < 形.引数.length - 1) 中 += (区[m] || '') + ',';
        }
        return 空 + 形.名 + '(' + 中 + 閉 + ')';
      }
      case '配': return 空 + '{' + 形.行.map(function (行) { return 行.map(字に戻す).join(','); }).join(';') + '}';
      default: return '';
    }
  }

  return { 形にする: 形にする, 字に戻す: 字に戻す, 強さ: 強さ };
});
