/** ★式を ほどく★（`=TEXT(…,"yyyy-mm-dd")` の 包みを 剥がして 中身を 返す）
 *  返り … { 名, 引数の字, 字包み } ／ 読めなければ null */
export function 式をほどく(式) {
  const 字包み = 式.match(/^=TEXT\((.+),"yyyy-mm-dd"\)$/);
  const 中 = 字包み ? '=' + 字包み[1] : 式;
  const m = 中.match(/^=([A-Z.]+)\((.*)\)$/);
  if (!m) return null;
  return { 名: m[1], 引数の字: m[2], 字包み: !!字包み };
}

/** ★出た 答えが 紙と 合うかを 見る★（★これが 物差し★）
 *  ・`出` … 数／字／`{誤り:'…'}`
 *  ・`行` … 紙の 1行 { 答, 型 }
 *  ★日付の 字に する のは 呼ぶ側で 済ませてから 渡して ください★ */
export function 答えを見る(出, 行) {
  if (出 && 出.誤り) {
    const 合 = String(行.答) === '#' + 出.誤り + '!' || String(行.答) === '#' + 出.誤り;
    return { 合: 合, 出: '#' + 出.誤り + '!' };
  }
  if (行.型 === 'Double') {
    const 正 = Number(行.答);
    return { 合: Math.abs(出 - 正) <= Math.max(1e-9, Math.abs(正) * 1e-9), 出: String(出) };
  }
  return { 合: String(出) === String(行.答), 出: String(出) };
}
