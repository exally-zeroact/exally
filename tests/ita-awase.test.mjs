/* ita-awase.test.mjs — ★板の 写しの 門★（2026-09-18）
 *
 *  ★★何を 守るか★★
 *    ㋑（計算を 台に 回す）では ★台が 板を 持ちます★。
 *    ＝★マスを 打つ たびに 台にも 打つ★
 *    ⇒★1つ 忘れると ★黙って 古い 値★が 出ます★
 *      ＝誤りに ならない／画面も 崩れない／★数だけ 違う★
 *      ＝★一番 見つけにくい 形★（記憶 `imi_no_nai_kazu_wa_ichiban_mitsukenikui`）
 *    ⇒★★だから 書く 前に 門を 作ります★★
 *
 *  ★★3つとも 出します★★（経営者1 の 注文）
 *    ・★式の 数★（画面の 側 ／ 台の 側）
 *    ・★値の 数★（同上）
 *    ・★★食い違った マスの 数★★
 *
 *  ★★わざと 壊します★★（記憶 `mon_wa_hikitsugarenai`＝★足したら その場で わざと 壊す★）
 *    ・★1マス ずらす★（式を 1文字 変える）⇒★赤に なる★
 *    ・★台にだけ 在る★（画面から 消す）  ⇒★赤に なる★
 *    ・★画面にだけ 在る★（台に 打たない）⇒★赤に なる★
 *    ⇒★★「壊したのに 赤に ならない」を ここで 潰します★★
 *
 *  使い方: node tests/ita-awase.test.mjs
 */
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require_ = createRequire(path.join(ROOT, 'package.json'));
const H = require_(path.join(ROOT, 'lib/shiki-hyou.js'));
const A = require_(path.join(ROOT, 'lib/shiki-ita-awase.js'));

let pass = 0, fail = 0;
const T = (n, よい, 添え) => {
  if (よい) { pass++; console.log('  ok   ' + n); }
  else { fail++; console.log('  NG   ' + n + (添え ? '\n       ' + 添え : '')); }
};

console.log('');
console.log('[ita-awase] ★板の 写しの 門★');

/* ★★マスの 名前★★（★台と 同じ 出し方か 先に 見ます★） */
console.log('');
console.log('■ ★マスの 名前★');
T('★A1★', A.番地から名(0, 0) === 'A1', A.番地から名(0, 0));
T('★Z1★', A.番地から名(0, 25) === 'Z1', A.番地から名(0, 25));
T('★★AA1★★（★26で 繰り上がる★）', A.番地から名(0, 26) === 'AA1', A.番地から名(0, 26));
T('★★AZ10★★', A.番地から名(9, 51) === 'AZ10', A.番地から名(9, 51));
T('★★BA10★★', A.番地から名(9, 52) === 'BA10', A.番地から名(9, 52));

/* ★★打った 物★★（★答えでは なく 打った 物★） */
console.log('');
console.log('■ ★打った 物を 字に する★');
T('★式は f★', A.打った物({ f: '=A1*2', v: 2, d: 2 }) === '=A1*2');
T('★値は v★', A.打った物({ v: '1', d: 1 }) === '1');
T('★★0 も 値★★（★空では ありません★）', A.打った物({ v: 0 }) === '0', A.打った物({ v: 0 }));
T('★空は 空の 字★', A.打った物({}) === '' && A.打った物(null) === '');

/* ── ★材料★ ── */
const 材料 = () => {
  const h = H.表();
  h.打つ('A1', '1');
  h.打つ('A2', '2');
  h.打つ('B1', '=A1*2');
  h.打つ('B2', '=A2+A1');
  h.打つ('C1', 'あ');
  return h;
};
const 紙 = () => ({
  '0,0': { v: '1', d: 1 },
  '1,0': { v: '2', d: 2 },
  '0,1': { f: '=A1*2', v: 2, d: 2 },
  '1,1': { f: '=A2+A1', v: 3, d: 3 },
  '0,2': { v: 'あ', d: 'あ' },
});

/* ★★①合って いる 時★★ */
console.log('');
console.log('■ ★①合って いる 時★');
{
  const 出 = A.数える(材料(), 紙());
  console.log('   ★式★ 画面 ' + 出.式.紙 + ' / 台 ' + 出.式.台
    + ' ★値★ 画面 ' + 出.値.紙 + ' / 台 ' + 出.値.台
    + ' ★食い違い★ ' + 出.食い違い);
  T('★★式の 数が 3つとも 出る★★（画面 2 / 台 2）', 出.式.紙 === 2 && 出.式.台 === 2,
    JSON.stringify(出.式));
  T('★★値の 数が 出る★★（画面 3 / 台 3）', 出.値.紙 === 3 && 出.値.台 === 3,
    JSON.stringify(出.値));
  T('★★食い違い 0★★', 出.食い違い === 0, JSON.stringify(出.中身));
}

/* ★★②わざと 1マス ずらす★★（★足しただけでは 効かない＝門は 引き継がれない★） */
console.log('');
console.log('■ ★★②わざと 1マス ずらす★★（★赤に なるのを 見せます★）');
{
  const d = 紙();
  d['1,1'] = { f: '=A2+A1+1', v: 4, d: 4 };   /* ★台は `=A2+A1` の まま★ */
  const 出 = A.数える(材料(), d);
  console.log('   ★食い違い★ ' + 出.食い違い + ' ／ ★中身★ ' + JSON.stringify(出.中身));
  T('★★ずらしたら 食い違いが 1★★', 出.食い違い === 1, String(出.食い違い));
  T('★★どの マスかを 名指しで 出す★★（B2）',
    出.中身.length === 1 && 出.中身[0].マス === 'B2', JSON.stringify(出.中身));
  T('★★画面と 台の 字を 両方 出す★★',
    出.中身[0] && 出.中身[0].画面 === '=A2+A1+1' && 出.中身[0].台 === '=A2+A1',
    JSON.stringify(出.中身[0]));
}

/* ★★③台にだけ 在る★★（★画面から 消したのに 台に 残った★＝黙って 古い 値が 出る 形） */
console.log('');
console.log('■ ★★③台にだけ 在る★★（★消し忘れ★）');
{
  const d = 紙();
  delete d['1,1'];
  const 出 = A.数える(材料(), d);
  console.log('   ★式★ 画面 ' + 出.式.紙 + ' / 台 ' + 出.式.台 + ' ★食い違い★ ' + 出.食い違い);
  T('★★食い違いが 1★★', 出.食い違い === 1, String(出.食い違い));
  T('★★画面が (無い) と 出る★★',
    出.中身.length === 1 && 出.中身[0].マス === 'B2' && 出.中身[0].画面 === '(無い)',
    JSON.stringify(出.中身));
  T('★★式の 数が 割れる★★（画面 1 / 台 2）', 出.式.紙 === 1 && 出.式.台 === 2,
    JSON.stringify(出.式));
}

/* ★★④画面にだけ 在る★★（★台に 打ち忘れた★＝ここが ㋑で 一番 起きる 形） */
console.log('');
console.log('■ ★★④画面にだけ 在る★★（★台への 打ち忘れ★）');
{
  const h = 材料();
  const d = 紙();
  d['2,1'] = { f: '=B1+B2', v: 5, d: 5 };   /* ★B3＝台に 打って いない★ */
  const 出 = A.数える(h, d);
  console.log('   ★式★ 画面 ' + 出.式.紙 + ' / 台 ' + 出.式.台 + ' ★食い違い★ ' + 出.食い違い);
  T('★★食い違いが 1★★', 出.食い違い === 1, String(出.食い違い));
  T('★★台が 空と 出る★★',
    出.中身.length === 1 && 出.中身[0].マス === 'B3' && 出.中身[0].台 === '',
    JSON.stringify(出.中身));
  T('★★式の 数が 割れる★★（画面 3 / 台 2）', 出.式.紙 === 3 && 出.式.台 === 2,
    JSON.stringify(出.式));
}

/* ★★⑤溢れで 埋まった マスは 数えない★★
     ＝★`d` だけ 在って `f` も `v` も 無い マス★（★打った 物では ありません★） */
console.log('');
console.log('■ ★⑤溢れで 埋まった マスは 数えない★');
{
  const d = 紙();
  d['0,3'] = { d: 7 };   /* ★溢れ先★ */
  const 出 = A.数える(材料(), d);
  T('★★食い違い 0 の まま★★（★溢れ先を 数えない★）', 出.食い違い === 0, JSON.stringify(出.中身));
  T('★値の 数も 増えない★（画面 3）', 出.値.紙 === 3, String(出.値.紙));
}

/* ★★⑥読めない 時は 黙って 緑に しない★★ */
console.log('');
console.log('■ ★⑥読めない 時★');
{
  const 出 = A.数える(null, 紙());
  T('★★板が 無ければ 読めないと 出す★★', 出.読めない === true, JSON.stringify(出));
}

console.log('');
console.log('★合計★ ok ' + pass + ' / NG ' + fail);
process.exit(fail === 0 ? 0 : 1);
